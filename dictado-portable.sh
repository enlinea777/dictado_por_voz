#!/usr/bin/env bash
# ────────────────────────────────────────────────────────────────────────────
# dictado-portable.sh  —  Instalador + ejecutor del widget de dictado por voz
#
# Uso:
#   chmod +x dictado-portable.sh
#   ./dictado-portable.sh
#
# En el primer arranque instala dependencias y crea un entorno virtual en
# ~/.local/share/dictado-venv/.  Las siguientes ejecuciones son inmediatas.
#
# X11 y Wayland: en Wayland el atajo global usa el portal GlobalShortcuts y
# el texto se pega con uinput (evdev); en X11 se mantiene XGrabKey + xdotool.
# ────────────────────────────────────────────────────────────────────────────
set -euo pipefail

VENV_DIR="${HOME}/.local/share/dictado-venv"
APP_DIR="${HOME}/.local/share/dictado"
PY_FILE="${APP_DIR}/dictado.py"

IS_WAYLAND=0
[[ "${XDG_SESSION_TYPE:-}" == "wayland" || -n "${WAYLAND_DISPLAY:-}" ]] && IS_WAYLAND=1

# ── 1. Python 3 disponible ────────────────────────────────────────────────
if ! command -v python3 &>/dev/null; then
    echo "ERROR: Python 3 no encontrado. Instálalo con:"
    echo "  sudo apt install python3 python3-pip python3-venv"
    exit 1
fi

PY_VER=$(python3 -c "import sys; print(sys.version_info.minor)")
if [[ "$PY_VER" -lt 9 ]]; then
    echo "Se requiere Python 3.9+. Versión detectada: 3.${PY_VER}"
    exit 1
fi

# ── 2. Dependencias de sistema ────────────────────────────────────────────
MISSING=()
command -v xdotool  &>/dev/null || MISSING+=("xdotool")
command -v xclip    &>/dev/null || MISSING+=("xclip")
python3 -c "import tkinter" 2>/dev/null || MISSING+=("python3-tk")
if (( IS_WAYLAND )); then
    # wl-copy: portapapeles nativo de Wayland (imprescindible para pegar)
    command -v wl-copy &>/dev/null || MISSING+=("wl-clipboard")
fi

if [[ ${#MISSING[@]} -gt 0 ]]; then
    echo "Instalando dependencias del sistema: ${MISSING[*]}"
    if command -v apt-get &>/dev/null; then
        sudo apt-get install -y "${MISSING[@]}" portaudio19-dev libportaudio2
    else
        echo "Instala manualmente: ${MISSING[*]}  portaudio19-dev"
        echo "Ejemplo (Fedora):  sudo dnf install ${MISSING[*]} portaudio-devel wl-clipboard"
        exit 1
    fi
fi

# ── 3. Entorno virtual + pip ──────────────────────────────────────────────
# Un cambio de versión de Python (p. ej. 3.12 → 3.14) deja el venv roto:
# los paquetes quedan en lib/python3.X y el intérprete ya no los ve.
if [[ -d "${VENV_DIR}" ]] && ! "${VENV_DIR}/bin/python3" -c "import sys" &>/dev/null; then
    echo "El entorno virtual ${VENV_DIR} está roto (¿cambió Python?): se recrea."
    rm -rf "${VENV_DIR}"
fi
if [[ ! -d "${VENV_DIR}" ]]; then
    echo "Creando entorno virtual en ${VENV_DIR} …"
    python3 -m venv "${VENV_DIR}"
fi

PY="${VENV_DIR}/bin/python3"
PIP="${VENV_DIR}/bin/pip"

# Actualizar pip silenciosamente
"$PIP" install --quiet --upgrade pip

# Instalar paquetes Python si falta alguno
NEEDS_INSTALL=false
for pkg in sounddevice numpy pyperclip pynput pystray PIL Xlib evdev dbus_fast; do
    "$PY" -c "import ${pkg}" 2>/dev/null || NEEDS_INSTALL=true
done
# websocket-client se importa como 'websocket'
"$PY" -c "import websocket" 2>/dev/null || NEEDS_INSTALL=true

if [[ "$NEEDS_INSTALL" == "true" ]]; then
    echo "Instalando paquetes Python …"
    "$PIP" install --quiet \
        "websocket-client>=1.6" \
        "sounddevice>=0.4" \
        "numpy>=1.20" \
        "pyperclip>=1.8" \
        "pynput>=1.7" \
        "python-xlib>=0.33" \
        "pystray>=0.19" \
        "Pillow>=9.0" \
        "evdev>=1.6" \
        "dbus-fast>=5.0"
fi

# ── 4. Extraer script Python ──────────────────────────────────────────────
mkdir -p "${APP_DIR}"

# El script Python está codificado en base64 al final de este archivo.
# Se extrae y actualiza en cada ejecución (garantiza última versión).
SELF="$(realpath "${BASH_SOURCE[0]}")"
B64_MARKER="# __DICTADO_PY_BASE64__"
B64_LINE=$(grep -n "^${B64_MARKER}$" "$SELF" | cut -d: -f1 | head -1)
if [[ -n "$B64_LINE" ]]; then
    tail -n "+$((B64_LINE + 1))" "$SELF" | base64 -d > "${PY_FILE}"
else
    echo "ERROR: No se encontró el bloque Python embebido en este script."
    exit 1
fi

# ── 5. Ejecutar ──────────────────────────────────────────────────────────
# En Wayland el portal GlobalShortcuts necesita que el proceso tenga un
# 'app id'; systemd lo deduce del scope 'app-dictado-<aleatorio>.scope'.
wayland_scope_needed() {
    (( IS_WAYLAND )) || return 1
    [[ -n "${DICTADO_IN_SCOPE:-}" ]] && return 1
    command -v systemd-run &>/dev/null || return 1
    local unit
    unit="$(head -1 /proc/self/cgroup 2>/dev/null)"
    unit="${unit##*:}"
    unit="${unit##*/}"
    [[ "$unit" != app-* ]]
}

if wayland_scope_needed; then
    export DICTADO_IN_SCOPE=1
    echo "Iniciando dictado (scope systemd para el atajo global) …"
    exec systemd-run --user --scope --quiet \
        --unit="app-dictado-$(printf '%06x' $((RANDOM * RANDOM))).scope" \
        "${SELF}" "$@"
fi

echo "Iniciando dictado …"
exec "${PY}" "${PY_FILE}" "$@"

